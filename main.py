#!/usr/bin/env python3
"""Finance Natural-Language-to-SQL — ask a finance question in plain English,
get back SQL, a plain-English explanation, and the rows it returns.

HOW SQL IS GENERATED — READ THIS FIRST
--------------------------------------
SQL is generated by DETERMINISTIC rules and templates in this file
(`translate_question`). No large language model (LLM) is called, no API key
is needed, and no network request is made. Every supported question shape
maps to one fixed, reviewed SQL template, so the output is fully
explainable and auditable — which is what a Finance / regulated-data
environment needs.

There is a documented, pluggable LLM interface in this file
(`LLMTranslatorInterface`). That is where a real LLM API (for example
Snowflake Cortex, or another approved provider) would plug in later, behind
the same validation and human-confirmation steps. It is not wired up and
it is never called by default. Do not claim this tool uses an LLM: it does
not, unless someone deliberately implements that interface and turns it on.

SAFETY / GUARDRAILS
-------------------
1. Only SELECT statements are ever generated or run. Any question asking
   for a write (DELETE, UPDATE, DROP, INSERT, ALTER, TRUNCATE, CREATE,
   GRANT, REVOKE, ...) is rejected before anything runs.
2. Generated SQL is validated against the known schema (tables and literal
   vendor/department names must exist in the database).
3. Human-in-the-loop: before any SQL runs, the SQL and its explanation are
   shown and a human must confirm (type `y`). Use --auto-confirm only for
   the automated eval run, never as the normal way to run finance queries.
4. All data is SYNTHETIC (see data/ and README.md). Never point this at
   real finance data without a proper access review.

Usage:
    python3 main.py "total spend by department"
    python3 main.py --question "top 5 vendors by spend" --auto-confirm
    python3 main.py                       # interactive prompt
    python3 main.py --list-examples
    python3 main.py --eval                # run the eval set (auto-confirm)
    python3 main.py --question "..." --output output/result.txt

Only the Python standard library is used (sqlite3, argparse, csv, re, ...).
"""

import argparse
import csv
import os
import re
import sqlite3
import subprocess
import sys

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(PROJECT_ROOT, "data")
DEFAULT_DB = os.path.join(DATA_DIR, "finance.db")

ALLOWED_TABLES = {"transactions", "vendors", "departments", "monthly_close"}

FORBIDDEN_KEYWORDS = [
    "DELETE", "UPDATE", "DROP", "INSERT", "ALTER", "TRUNCATE", "CREATE",
    "GRANT", "REVOKE", "REPLACE", "MERGE", "VACUUM", "ATTACH", "DETACH",
    "PRAGMA",
]

# Words that name tables/columns which do NOT exist in this schema. A question
# using them must be rejected, not guessed at.
UNKNOWN_ENTITY_WORDS = [
    "payroll", "salary", "salaries", "employee", "employees",
    "pay slip", "payslip", "bonus payment", "tax return",
]

KNOWN_VENDORS = [
    "Northwind Cloud Services", "BluePeak Software",
    "Harbor Office Supplies", "Cascade Travel Group",
    "Meridian Consulting", "Apex Catering", "Silverline Marketing",
    "Granite Facilities Group", "BrightPath Training",
    "Keystone Legal Advisors", "Summit Hardware Co", "Riverbend Events",
]

KNOWN_DEPARTMENTS = [
    "Finance Operations", "Engineering", "People Operations", "Sales",
    "Marketing", "Customer Support", "Facilities", "Legal", "Product",
    "Data & Analytics",
]

MONTHS = {
    "january": "01", "february": "02", "march": "03", "april": "04",
    "may": "05", "june": "06", "july": "07", "august": "08",
    "september": "09", "october": "10", "november": "11", "december": "12",
}

EXAMPLE_QUESTIONS = [
    "total spend by department",
    "top 5 vendors by spend",
    "transactions over $1000",
    "count transactions by status",
    "total spend for Northwind Cloud Services",
    "average transaction amount by category",
    "monthly close totals for September 2026",
    "list transactions for the Engineering department",
    "total spend by category",
    "show flagged transactions",
    "total spend in September 2026",
]


# ---------------------------------------------------------------------------
# Pluggable LLM interface (NOT wired up — see module docstring)
# ---------------------------------------------------------------------------
class LLMTranslatorInterface:
    """Where a real LLM would plug in, if one is ever approved.

    To use a real LLM, implement ``translate`` so it calls the approved
    provider's API and returns a single SQL string, then pass an instance
    to ``translate_question(..., llm=...)``. The returned SQL still goes
    through exactly the same ``validate_sql`` checks and the same human
    confirmation step as the deterministic templates — the LLM never gets
    to skip validation. This interface is intentionally not implemented:
    calling it raises an error rather than silently pretending an LLM ran.
    """

    def translate(self, question):
        raise NotImplementedError(
            "No LLM is configured. SQL generation is deterministic and "
            "template-based by default. Implement LLMTranslatorInterface "
            "against an approved provider to enable LLM translation."
        )


# ---------------------------------------------------------------------------
# Deterministic translation: plain-English question -> (sql, explanation)
# ---------------------------------------------------------------------------
def _month_from_question(q):
    """Return 'YYYY-MM' if the question names a month, else None."""
    m = re.search(r"(20\d\d)-(\d{2})", q)
    if m:
        return f"{m.group(1)}-{m.group(2)}"
    m = re.search(
        r"(january|february|march|april|may|june|july|august|september|"
        r"october|november|december)\s+(20\d\d)", q)
    if m:
        return f"{m.group(2)}-{MONTHS[m.group(1)]}"
    return None


def _find_vendor(q):
    for name in KNOWN_VENDORS:
        if name.lower() in q:
            return name
    return None


def _find_department(q):
    for name in KNOWN_DEPARTMENTS:
        if name.lower() in q:
            return name
    return None


def translate_question(question, llm=None):
    """Translate a question into (sql, explanation).

    Returns (None, reason) when the question must be rejected:
    reason is 'UNSAFE' for write operations, 'UNKNOWN_SCHEMA' for a
    table/column that does not exist, or 'UNSUPPORTED' for anything else
    the templates do not cover. Nothing is executed in this function.
    """
    q = " ".join(question.strip().lower().split())
    if not q:
        return None, "UNSUPPORTED: empty question."

    # 1. Unsafe: any write operation, checked before anything else.
    for word in FORBIDDEN_KEYWORDS:
        if re.search(r"\b" + word.lower() + r"\b", q):
            return None, (
                f"UNSAFE: rejected — the question asks for '{word}', a "
                "write operation. This tool only runs read-only SELECT "
                "queries."
            )

    # 2. Unknown schema: names a table/column that does not exist here.
    for word in UNKNOWN_ENTITY_WORDS:
        if word in q:
            return None, (
                "UNKNOWN_SCHEMA: rejected — the question refers to "
                f"'{word}', which is not a table or column in this "
                "finance database. Known tables: transactions, vendors, "
                "departments, monthly_close."
            )

    # 3. Optional LLM path (not configured by default).
    if llm is not None:
        sql = llm.translate(question)
        return sql, ("SQL produced by the plugged-in LLM translator. "
                     "It still needs validation and human confirmation.")

    # 4. Deterministic templates, most specific first.
    if "monthly close" in q:
        month = _month_from_question(q)
        if month:
            sql = (
                "SELECT mc.close_month AS close_month, "
                "d.department_name AS department, mc.total_spend AS total_spend, "
                "mc.total_transactions AS total_transactions, "
                "mc.close_status AS close_status "
                "FROM monthly_close mc "
                "JOIN departments d ON mc.department_id = d.id "
                f"WHERE mc.close_month = '{month}' "
                "ORDER BY mc.total_spend DESC"
            )
            return sql, (
                f"Shows the monthly close totals for {month}: total spend, "
                "number of transactions, and close status for each "
                "department that closed that month."
            )
        return None, ("UNSUPPORTED: monthly close needs a month, "
                      "for example 'monthly close totals for September 2026'.")

    if "top" in q and "vendor" in q and "spend" in q:
        m = re.search(r"top\s+(\d+)", q)
        limit = int(m.group(1)) if m else 5
        sql = (
            "SELECT v.vendor_name AS vendor, SUM(t.amount) AS total_spend "
            "FROM transactions t "
            "JOIN vendors v ON t.vendor_id = v.id "
            "GROUP BY v.vendor_name "
            "ORDER BY total_spend DESC "
            f"LIMIT {limit}"
        )
        return sql, (
            f"Adds up all transaction amounts per vendor, sorts vendors "
            f"from highest to lowest spend, and shows the top {limit}."
        )

    if "total spend" in q or "total spending" in q:
        vendor = _find_vendor(q)
        if vendor:
            sql = (
                "SELECT v.vendor_name AS vendor, SUM(t.amount) AS total_spend "
                "FROM transactions t "
                "JOIN vendors v ON t.vendor_id = v.id "
                f"WHERE v.vendor_name = '{vendor}' "
                "GROUP BY v.vendor_name"
            )
            return sql, (
                f"Adds up every transaction amount for the vendor "
                f"'{vendor}'."
            )
        if "by department" in q:
            sql = (
                "SELECT d.department_name AS department, "
                "SUM(t.amount) AS total_spend "
                "FROM transactions t "
                "JOIN departments d ON t.department_id = d.id "
                "GROUP BY d.department_name "
                "ORDER BY total_spend DESC"
            )
            return sql, (
                "Adds up all transaction amounts for each department and "
                "lists departments from highest to lowest total spend."
            )
        if "by category" in q:
            sql = (
                "SELECT t.category AS category, SUM(t.amount) AS total_spend "
                "FROM transactions t "
                "GROUP BY t.category "
                "ORDER BY total_spend DESC"
            )
            return sql, (
                "Adds up all transaction amounts for each spending "
                "category and lists categories from highest to lowest."
            )
        month = _month_from_question(q)
        if month and (" in " in q or " for " in q):
            sql = (
                "SELECT SUM(t.amount) AS total_spend, "
                "COUNT(*) AS transaction_count "
                "FROM transactions t "
                f"WHERE strftime('%Y-%m', t.transaction_date) = '{month}'"
            )
            return sql, (
                f"Adds up all transaction amounts in {month} and counts "
                "how many transactions there were that month."
            )
        return None, ("UNSUPPORTED: 'total spend' needs a breakdown, "
                      "for example 'by department', 'by category', or "
                      "a vendor name.")

    if "average" in q and "by category" in q:
        sql = (
            "SELECT t.category AS category, "
            "ROUND(AVG(t.amount), 2) AS average_amount "
            "FROM transactions t "
            "GROUP BY t.category "
            "ORDER BY average_amount DESC"
        )
        return sql, (
            "Works out the average transaction amount for each spending "
            "category and lists categories from highest to lowest average."
        )

    if "count" in q and "by status" in q:
        sql = (
            "SELECT t.status AS status, COUNT(*) AS transaction_count "
            "FROM transactions t "
            "GROUP BY t.status "
            "ORDER BY transaction_count DESC"
        )
        return sql, (
            "Counts how many transactions have each status "
            "(Approved, Pending, Flagged)."
        )

    if "flagged" in q:
        sql = (
            "SELECT t.id AS id, t.transaction_date AS transaction_date, "
            "v.vendor_name AS vendor, d.department_name AS department, "
            "t.category AS category, t.description AS description, "
            "t.amount AS amount "
            "FROM transactions t "
            "JOIN vendors v ON t.vendor_id = v.id "
            "JOIN departments d ON t.department_id = d.id "
            "WHERE t.status = 'Flagged' "
            "ORDER BY t.amount DESC"
        )
        return sql, (
            "Lists every transaction marked Flagged, biggest amount first, "
            "so a human can review them."
        )

    amount_match = re.search(
        r"(over|above|more than|greater than)\s+\$?\s?([\d,]+(?:\.\d+)?)", q)
    if "transaction" in q and amount_match:
        amount = amount_match.group(2).replace(",", "")
        sql = (
            "SELECT t.id AS id, t.transaction_date AS transaction_date, "
            "v.vendor_name AS vendor, d.department_name AS department, "
            "t.category AS category, t.amount AS amount, t.status AS status "
            "FROM transactions t "
            "JOIN vendors v ON t.vendor_id = v.id "
            "JOIN departments d ON t.department_id = d.id "
            f"WHERE t.amount > {amount} "
            "ORDER BY t.amount DESC"
        )
        return sql, (
            f"Lists every transaction with an amount over ${amount}, "
            "biggest amount first."
        )

    if "transaction" in q:
        dept = _find_department(q)
        if dept:
            sql = (
                "SELECT t.id AS id, t.transaction_date AS transaction_date, "
                "v.vendor_name AS vendor, t.category AS category, "
                "t.description AS description, t.amount AS amount, "
                "t.status AS status "
                "FROM transactions t "
                "JOIN vendors v ON t.vendor_id = v.id "
                "JOIN departments d ON t.department_id = d.id "
                f"WHERE d.department_name = '{dept}' "
                "ORDER BY t.transaction_date"
            )
            return sql, (
                f"Lists every transaction for the {dept} department, "
                "oldest first."
            )

    return None, (
        "UNSUPPORTED: this question does not match any supported pattern. "
        "Try one of the examples from --list-examples."
    )


# ---------------------------------------------------------------------------
# Validation: read-only + schema checks (runs on every generated SQL)
# ---------------------------------------------------------------------------
def validate_sql(sql, conn):
    """Return (ok, message). `ok` is False when the SQL must not run."""
    cleaned = sql.strip()
    if not cleaned.upper().startswith("SELECT"):
        return False, "Validation failed: only SELECT statements may run."
    if ";" in cleaned.rstrip(";") or cleaned.count(";") > 1:
        return False, ("Validation failed: multiple statements are not "
                       "allowed.")
    upper = cleaned.upper()
    for word in FORBIDDEN_KEYWORDS:
        if re.search(r"\b" + word + r"\b", upper):
            return False, (f"Validation failed: forbidden keyword '{word}' "
                           "found in SQL.")
    tables = set(t.lower() for t in re.findall(
        r"(?:FROM|JOIN)\s+([A-Za-z_][A-Za-z0-9_]*)", cleaned, re.IGNORECASE))
    unknown_tables = tables - ALLOWED_TABLES
    if unknown_tables:
        return False, (f"Validation failed: unknown table(s) "
                       f"{sorted(unknown_tables)}.")
    # Literal vendor/department names in the SQL must exist in the database.
    for name in re.findall(r"vendor_name\s*=\s*'([^']+)'", cleaned):
        row = conn.execute(
            "SELECT COUNT(*) FROM vendors WHERE vendor_name = ?", (name,)
        ).fetchone()
        if row[0] == 0:
            return False, (f"Validation failed: vendor '{name}' does not "
                           "exist in the database.")
    for name in re.findall(r"department_name\s*=\s*'([^']+)'", cleaned):
        row = conn.execute(
            "SELECT COUNT(*) FROM departments WHERE department_name = ?",
            (name,)
        ).fetchone()
        if row[0] == 0:
            return False, (f"Validation failed: department '{name}' does "
                           "not exist in the database.")
    return True, "Validation passed: read-only SELECT on known tables."


# ---------------------------------------------------------------------------
# Database setup + running
# ---------------------------------------------------------------------------
def ensure_db(db_path):
    """Build the synthetic database from CSVs if it does not exist yet."""
    if os.path.exists(db_path):
        return
    print(f"Database not found at {db_path} — building it from data/*.csv ...")
    script = os.path.join(DATA_DIR, "build_db.py")
    result = subprocess.run(
        [sys.executable, script, "--db", db_path],
        capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stdout)
        print(result.stderr, file=sys.stderr)
        raise SystemExit("Failed to build the synthetic database.")
    print(result.stdout)


def ask_human(sql, explanation):
    """Human-in-the-loop checkpoint. Returns True only on an explicit yes."""
    print("\n--- Human check (required before running) ---")
    print("SQL to run:")
    print(f"  {sql}")
    print("What it means:")
    print(f"  {explanation}")
    answer = input("Run this SQL? Type 'y' to run, anything else to stop: ")
    return answer.strip().lower() in ("y", "yes")


def run_question(question, db_path=DEFAULT_DB, auto_confirm=False,
                 output_path=None):
    """Full flow for one question. Returns a dict describing the outcome."""
    ensure_db(db_path)
    sql, explanation = translate_question(question)
    if sql is None:
        print(f"\nRejected: {explanation}")
        return {"question": question, "sql": None, "rejected": True,
                "reason": explanation, "rows": [], "columns": []}

    conn = sqlite3.connect(db_path)
    try:
        ok, message = validate_sql(sql, conn)
        print(f"\n{message}")
        if not ok:
            return {"question": question, "sql": sql, "rejected": True,
                    "reason": message, "rows": [], "columns": []}
        print(f"\nGenerated SQL:\n  {sql}")
        print(f"\nPlain-English explanation:\n  {explanation}")
        if not auto_confirm:
            if not ask_human(sql, explanation):
                print("\nStopped by the human check — nothing was run.")
                return {"question": question, "sql": sql, "rejected": True,
                        "reason": "Stopped at human confirmation step.",
                        "rows": [], "columns": []}
        else:
            print("\n(--auto-confirm: human check skipped for this run.)")
        cursor = conn.execute(sql)
        columns = [d[0] for d in cursor.description]
        rows = cursor.fetchall()
    finally:
        conn.close()

    print(f"\nResults ({len(rows)} row(s)):")
    print(" | ".join(columns))
    for row in rows:
        print(" | ".join(str(v) for v in row))
    if output_path:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)),
                    exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(f"Question: {question}\n\nSQL:\n{sql}\n\n")
            f.write(f"Explanation:\n{explanation}\n\n")
            f.write(f"Results ({len(rows)} row(s)):\n")
            f.write(" | ".join(columns) + "\n")
            for row in rows:
                f.write(" | ".join(str(v) for v in row) + "\n")
        print(f"\nWrote results to {output_path}")
    return {"question": question, "sql": sql, "rejected": False,
            "reason": "", "rows": rows, "columns": columns}


def main():
    parser = argparse.ArgumentParser(
        description="Finance natural-language-to-SQL (deterministic, "
                    "read-only, human-in-the-loop).")
    parser.add_argument("question", nargs="?", default=None,
                        help="Plain-English finance question.")
    parser.add_argument("--question", dest="question_flag", default=None,
                        help="Plain-English finance question.")
    parser.add_argument("--auto-confirm", action="store_true",
                        help="Skip the human confirmation step. Only for "
                             "the automated eval run.")
    parser.add_argument("--db", default=DEFAULT_DB,
                        help="SQLite database path (default: data/finance.db).")
    parser.add_argument("--output", default=None,
                        help="Write SQL, explanation and rows to this file.")
    parser.add_argument("--list-examples", action="store_true",
                        help="Print example questions and exit.")
    parser.add_argument("--eval", action="store_true",
                        help="Run the eval set in evals/ (auto-confirm) "
                             "and exit.")
    args = parser.parse_args()

    if args.list_examples:
        print("Example questions:")
        for example in EXAMPLE_QUESTIONS:
            print(f"  - {example}")
        return 0

    if args.eval:
        eval_script = os.path.join(PROJECT_ROOT, "evals", "eval.py")
        result = subprocess.run([sys.executable, eval_script])
        return result.returncode

    question = args.question_flag or args.question
    if not question:
        question = input("Ask a finance question in plain English: ").strip()
    if not question:
        print("No question given. Try --list-examples for ideas.")
        return 1

    outcome = run_question(question, db_path=args.db,
                           auto_confirm=args.auto_confirm,
                           output_path=args.output)
    return 0 if not outcome["rejected"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
